// 4. Switch Statement
console.log("\nExample 4: Switch Statement");
let day = "Wednesday";
switch (day) {
    case "Monday":
        console.log("It's the start of the week!");
        break;
    case "Wednesday":
        console.log("It's midweek!");
        break;
    case "Friday":
        console.log("Weekend is near!");
        break;
    default:
        console.log("It's another day.");
}