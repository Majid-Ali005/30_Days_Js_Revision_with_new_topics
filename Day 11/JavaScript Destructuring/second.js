// Object Destructuring
let user = { id: 1, name: "Alice" };
let { id, name } = user;
console.log(id, name); // 1 Alice

// Array Destructuring
let numbers = [10, 20, 30];
let [first, second] = numbers;
console.log(first, second); // 10 20

